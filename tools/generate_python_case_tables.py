"""Pin object-rule and discipline case behavior to Python 3.11 / Unicode 14."""
from pathlib import Path
import json
import unicodedata

assert unicodedata.unidata_version == "14.0.0"
root = Path(__file__).resolve().parents[1]
text = "// Python 3.11 / Unicode 14; generated by tools/generate_python_case_tables.py.\n"
for table, method in [("UPPER", str.upper), ("CASEFOLD", str.casefold)]:
    text += f"pub const {table}: &[(char, &str)] = &[\n"
    for number in range(0x110000):
        char = chr(number)
        mapped = method(char)
        if mapped != char:
            text += f"('\\u{{{number:x}}}', {json.dumps(mapped, ensure_ascii=False)}),\n"
    text += "];\n"
(root / "rust/src/python_case_unicode.rs").write_text(text, encoding="utf-8", newline="\n")
