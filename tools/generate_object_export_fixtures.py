def reference():
    package = types.ModuleType("_sleufbase_export_reference")
    package.__path__ = [str(ROOT)]
    sys.modules[package.__name__] = package
    return importlib.import_module(package.__name__ + ".kickthemap_dxf_export")

def signature(path):
    doc = ezdxf.readfile(path)
    audit = doc.audit()
    if audit.has_errors:
        raise RuntimeError(audit.errors)
    entities = []
    for entity in doc.modelspace():
        kind = entity.dxftype()
        record = {"kind":kind,"layer":entity.dxf.layer,"color":entity.dxf.color}
        if kind == "LINE":
            record["points"] = [list(entity.dxf.start),list(entity.dxf.end)]
        elif kind == "POLYLINE":
            record["points"] = [list(v.dxf.location) for v in entity.vertices]
            record["closed"] = bool(entity.is_closed)
        elif kind == "TEXT":
            record.update(text=entity.dxf.text,height=entity.dxf.height,style=entity.dxf.style,
                align=[entity.dxf.halign,entity.dxf.valign],points=[list(entity.dxf.insert),list(entity.dxf.align_point)],true_color=entity.dxf.true_color)
        if entity.has_xdata("KTM_DXF_EXPORT"):
            record["xdata"] = [tag.value for tag in entity.get_xdata("KTM_DXF_EXPORT")]
        entities.append(record)
    layers = {layer.dxf.name:{"color":layer.color,"true_color":layer.dxf.get("true_color")} for layer in doc.layers if layer.dxf.name != "Defpoints"}
    return {"entities":entities,"layers":layers,"font":doc.styles.get("PROEFSLEUVEN_LIBMONO").dxf.font,"units":doc.units}

def envelope(ref):
    doc = ezdxf.new("R2018")
    doc.units = 6
    doc.appids.add(ref.APP_ID)
    ref.KickTheMapDxfExporter()._setup_text_style(doc)
    doc.layers.remove("Defpoints")
    stream = io.StringIO()
    doc.write(stream)
    lines = stream.getvalue().splitlines()
    tags = list(zip(lines[::2],lines[1::2]))
    assert all(int(value,16)<0x1000 for code,value in tags if int(code) in (5,105) and value != doc.header["$HANDSEED"])
    text = []
    layer_table = False
    marker_count = 0
    in_header = False
    keep_header = True
    for i,(code,value) in enumerate(tags):
        c = int(code)
        if c==2 and value=="HEADER":in_header=True
        if in_header and c==0 and value=="ENDSEC":in_header=False;keep_header=True
        if in_header and c==9:keep_header=value in {"$ACADVER","$DWGCODEPAGE","$HANDSEED","$INSUNITS","$EXTMIN","$EXTMAX","$MEASUREMENT"}
        if not keep_header:continue
        if c == 9 and value in ("$EXTMIN","$EXTMAX"):
            text.extend([code,value])
            continue
        # Substitute only the six header values, preserving all other structure.
        variable = next((v for cc,v in reversed(tags[:i]) if int(cc)==9),"")
        if c in (10,20,30) and variable in ("$EXTMIN","$EXTMAX"):
            value = f"__SB_{variable[1:]}_{'XYZ'[(c-10)//10]}__"
        if i and int(tags[i-1][0])==9 and tags[i-1][1]=="$HANDSEED":value="FFFFFFFF"
        if value in ("CREATED_BY_EZDXF","WRITTEN_BY_EZDXF"):value=value.replace("EZDXF","SLEUFBASE")
        if value=="0.0 @ 2000-01-01T00:00:00.000000+00:00":value="SleufBase Rust; structural envelope: ezdxf 1.4.4"
        if c == 0 and value == "TABLE" and tags[i+1][1] == "LAYER":layer_table=True
        if layer_table and c == 70:value="__SB_LAYER_COUNT__";layer_table=False
        if c == 0 and value == "ENDTAB" and any(int(cc)==2 and v=="LAYER" for cc,v in tags[max(0,i-20):i]):
            # Layer 0 is the only original layer record.
            text.append("__SB_LAYERS__");marker_count+=1
        text.extend([code,value])
        if c == 2 and value == "ENTITIES":text.append("__SB_ENTITIES__");marker_count+=1
    assert marker_count == 2
    base = "\n".join(text)+"\n"
    (ROOT/"rust/src/object_dxf_base.txt").write_text(base,encoding="utf-8",newline="\n")
    constants = f'// Generated by tools/generate_object_export_fixtures.py; ezdxf 1.4.4.\npub const MODEL_SPACE: &str = "{doc.modelspace().layout_key}";\npub const LAYER_TABLE: &str = "{doc.layers.head.dxf.handle}";\n'
    (ROOT/"rust/src/object_dxf_handles.rs").write_text(constants,encoding="utf-8")

def unicode_tables():
    assert unicodedata.unidata_version == "14.0.0"
    zeros=[c for c in range(0x110000) if unicodedata.decimal(chr(c),None)==0]
    ranges=[]
    for c in range(0x110000):
        if chr(c).isalnum() or chr(c)=="_":
            if ranges and ranges[-1][1]==c-1:ranges[-1][1]=c
            else:ranges.append([c,c])
    text='// Python 3.11 Unicode 14 decimal digits and re Unicode word boundaries.\n// Generated from the reference standard library; not locale dependent.\n'
    text+='pub const DECIMAL_ZEROS: &[u32] = &['+','.join(hex(c) for c in zeros)+'];\n'
    text+='pub const WORD_RANGES: &[(u32,u32)] = &[\n'+''.join(f'({hex(a)},{hex(b)}),\n' for a,b in ranges)+'];\n'
    (ROOT/"rust/src/export_unicode.rs").write_text(text,encoding="utf-8")

